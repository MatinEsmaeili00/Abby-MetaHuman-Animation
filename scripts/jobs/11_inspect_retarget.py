import unreal
RTG = unreal.load_asset("/Game/Abby_Animation/RetargetAssets/RTG_AutoGenerated")
c = unreal.IKRetargeterController.get_controller(RTG)
print("controller methods:", [m for m in dir(c) if not m.startswith("_") and any(k in m for k in ("op","chain","pose","root","rig","settings","mesh"))][:120])
for side in (unreal.RetargetSourceOrTarget.SOURCE, unreal.RetargetSourceOrTarget.TARGET):
    rig = c.get_ik_rig(side)
    print(side, rig.get_path_name() if rig else None)
    if rig:
        rc = unreal.IKRigController.get_controller(rig)
        print("  mesh", rc.get_skeletal_mesh().get_path_name() if rc.get_skeletal_mesh() else None)
        print("  root", rc.get_retarget_root())
        chains = rc.get_retarget_chains()
        if chains: print("  BoneChain fields:", [x for x in dir(chains[0]) if not x.startswith("_") and not x.startswith("get") and not x.startswith("set")][:20])
        for ch in chains:
            d = {k: str(getattr(ch, k)) for k in dir(ch) if k in ("chain_name","start_bone","end_bone","ik_goal_name","start","end","goal")}
            print("  chain", d)
        print("  goals", [str(g.get_editor_property("goal_name")) for g in rc.get_all_goals()])
        print("  solvers", rc.get_num_solvers())
try:
    print("retarget pose names src:", [str(n) for n in c.get_retarget_poses(unreal.RetargetSourceOrTarget.SOURCE)])
    print("retarget pose names tgt:", [str(n) for n in c.get_retarget_poses(unreal.RetargetSourceOrTarget.TARGET)])
except Exception as e:
    print("poses:", e)
for p in ["/Game/Abby_Animation/New/AbbyWalking_Anim", "/Game/Abby_Animation/New/AbbyJogging", "/Game/Abby_Animation/New/AbbyRunning__2_",
          "/Game/Animation2/Walking_Anim", "/Game/Animation2/Jogging", "/Game/Animation2/Running__2_"]:
    a = unreal.load_asset(p)
    if not a: print("missing", p); continue
    print(p.split('/')[-1], "len", round(a.get_play_length(), 3), "rootmotion", a.get_editor_property("enable_root_motion"),
          "rootlock", a.get_editor_property("force_root_lock"), "skeleton", a.get_skeleton().get_name(),
          "frames", unreal.AnimationLibrary.get_num_frames(a))
src = unreal.load_asset("/Game/Animation2/Walking")
print("source mesh class", type(src).__name__)
