import unreal
EAL = unreal.EditorAssetLibrary
SRC_RTG = "/Game/Abby_Animation/RetargetAssets/RTG_AutoGenerated"
FIX_DIR = "/Game/Abby_Animation/Fixed"
RTG_PATH = FIX_DIR + "/RTG_Mixamo_To_Abby_Fixed"
POSE = "Aligned_To_Mixamo_TPose"
T = unreal.RetargetSourceOrTarget.TARGET

if not EAL.does_directory_exist(FIX_DIR):
    EAL.make_directory(FIX_DIR)
if not EAL.does_asset_exist(RTG_PATH):
    EAL.duplicate_asset(SRC_RTG, RTG_PATH)
rtg = unreal.load_asset(RTG_PATH)
c = unreal.IKRetargeterController.get_controller(rtg)

# 1) Target retarget pose: align Abby's chains (A-pose) to the Mixamo source chains (T-pose)
if POSE not in [str(p) for p in c.get_retarget_poses(T)]:
    c.create_retarget_pose(POSE, T)
c.set_current_retarget_pose(POSE, T)
c.reset_retarget_pose(POSE, [], T)
c.auto_align_all_bones(T, unreal.RetargetAutoAlignMethod.CHAIN_TO_CHAIN)
c.snap_bone_to_ground("ball_l", T)
for b in ["upperarm_l", "lowerarm_l", "hand_l", "thigh_l", "calf_l", "foot_l"]:
    q = c.get_rotation_offset_for_retarget_pose_bone(b, T)
    print(f"retarget pose offset {b}: {q.rotator()}")
print("root offset", c.get_root_offset_in_retarget_pose(T))
EAL.save_loaded_asset(rtg, only_if_is_dirty=False)

# 2) Batch retarget the Mixamo walk / jog / run onto Abby with the fixed retargeter
ar = unreal.AssetRegistryHelpers.get_asset_registry()
anims = [EAL.find_asset_data(p) for p in ["/Game/Animation2/Walking_Anim", "/Game/Animation2/Jogging", "/Game/Animation2/Running__2_"]]
inputs = unreal.IKRetargetBatchOperationInputs()
inputs.assets_to_retarget = anims
inputs.source_mesh = unreal.load_asset("/Game/Animation2/Walking")
inputs.target_mesh = unreal.load_asset("/Game/MetaHumans/MH_CH_Abby5/Body/SKM_MH_CH_Abby5_BodyMesh")
inputs.ik_retarget_asset = rtg
inputs.target_path = FIX_DIR
inputs.use_source_path = False
inputs.prefix = "Abby_"
inputs.suffix = "_Fixed"
inputs.include_referenced_assets = False
inputs.overwrite_existing_files = True
out = unreal.IKRetargetBatchOperation.run_batch_retarget(inputs)
for a in out:
    print("retargeted ->", a.package_name)
    EAL.save_asset(str(a.package_name), only_if_is_dirty=False)
