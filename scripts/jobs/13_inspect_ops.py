    oc = c.get_op_controller(i)
    print(i, name, "enabled", c.get_retarget_op_enabled(i), type(oc).__name__ if oc else None)
    if oc:
        try:
            st = oc.get_settings()
            print("    settings:", type(st).__name__, {k: str(getattr(st, k))[:80] for k in dir(st) if not k.startswith('_') and not callable(getattr(st, k, None))} )
        except Exception as e:
            print("    settings err", e)
